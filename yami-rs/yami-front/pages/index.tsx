const fetcher = (url, data) => fetch(url, {method: 'POST', body: data}).then(async (res) => [res.status, await res.text()])

export default function Home() {
  // const a = useSWR('http://localhost:5000/', fetcher)
  const a = useSWR(['api/yami', ')'], fetcher, {shouldRetryOnError: false})
  console.log(a.data, a.error)
  return (
    <div className="">
      <Head>
        <title>Create Next App</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <main className="">
        {JSON.stringify(a.data)}
        {JSON.stringify(a.error)}
        <Lane/>
      </main>
    </div>
  )
}

const Lane: React.VFC = () => {
  const [text, setText] = useState('')
  const {data} = useSWR(['api/yami', text], fetcher, {shouldRetryOnError: false})
  return (
    <div>
      <input type="text" value={text} onChange={e=> setText(e.target.value)}/>
      {text}
      {data?.[1]}
    </div>
  )
}
